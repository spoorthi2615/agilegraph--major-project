class SyntheticDevSandbox:
    """
    Isolated development environment for testing HeteroGATv2 model mechanics,
    training loops, checkpointing, and baseline comparisons using synthetic annotations.
    
    HARD SAFETY CONSTRAINTS:
    1. Every checkpoint, metric dictionary, and manifest is explicitly stamped:
       - is_synthetic_development_artifact: True
       - valid_for_empirical_claims: False
       - provenance: "SYNTHETIC_DEVELOPMENT_ONLY"
    2. Zero synthetic checkpoints or metrics are saved to production directories.
    3. Output directories are strictly quarantined under `dataset/synthetic_dev_sandbox/`.
    4. Genuine evaluation pipelines will reject any artifact generated by this sandbox.
    """

    SANDBOX_DIR = os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
        "dataset",
        "synthetic_dev_sandbox"
    )

    def __init__(self, seed: int = 42):
        self.seed = seed
        set_seed(seed)
        os.makedirs(self.SANDBOX_DIR, exist_ok=True)

    def generate_synthetic_development_dataset(
        self,
        package_assets: List[Dict[str, Any]],
        num_raters: int = 4
    ) -> Dict[str, Any]:
        """
        Generates simulated rater submissions and computes majority consensus labels
        strictly for mechanical pipeline testing.
        """
        rng = random.Random(self.seed)
        expert_ids = [f"dev_sim_rater_{i+1:02d}" for i in range(num_raters)]
        submissions = {exp_id: {"labels": []} for exp_id in expert_ids}
        consensus_labels = {}
        for asset in package_assets:
            aid = asset["asset_id"]
            # Deterministic pseudo-random label in {0, 1, 2} for smoke test mechanics
            label = rng.choice([0, 1, 2])
            consensus_labels[aid] = label
            for exp_id in expert_ids:
                submissions[exp_id]["labels"].append({"asset_id": aid, "label": label})

        manifest = {
            "is_synthetic_development_artifact": True,
            "valid_for_empirical_claims": False,
            "provenance": "SYNTHETIC_DEVELOPMENT_ONLY",
            "generation_timestamp": datetime.now(timezone.utc).isoformat(),
            "seed": self.seed,
            "num_simulated_raters": num_raters,
            "total_assets": len(package_assets),
            "consensus_labels": consensus_labels,
            "simulated_submissions": submissions
        }

        manifest_path = os.path.join(self.SANDBOX_DIR, "synthetic_dataset_manifest.json")
        with open(manifest_path, "w", encoding="utf-8") as f:
            json.dump(manifest, f, indent=2)

        return manifest

    def build_synthetic_pyg_data(
        self,
        ag: AgileGraph,
        consensus_labels: Dict[str, int],
        feature_config: FeatureConfig
    ) -> HeteroData:
        """
        Converts an AgileGraph to HeteroData injecting synthetic consensus labels
        into 'file' nodes for training loop verification.
        """
        data = HeteroData()
        node_maps = {}
        initialized_categories = set()

        for n_id, data_dict in ag.G.nodes(data=True):
            category = data_dict.get("category", "unknown_node")
            if category not in node_maps:
                node_maps[category] = {}
            current_idx = len(node_maps[category])
            node_maps[category][n_id] = current_idx

            if category not in initialized_categories:
                initialized_categories.add(category)
                data[category].x = []
                data[category].y = []
                data[category].node_ids = []

            props = data_dict.get("properties", data_dict)
            x_feat = extract_node_features(props, feature_config)
            
            # Label assignment: inject synthetic label if file node and present in consensus
            if category == "file":
                y_label = consensus_labels.get(n_id, -1)
            else:
                y_label = -1

            data[category].x.append(x_feat)
            data[category].y.append(y_label)
            data[category].node_ids.append(n_id)

        for category in node_maps.keys():
            if len(data[category].x) > 0:
                data[category].x = torch.stack(data[category].x)
                data[category].y = torch.tensor(data[category].y, dtype=torch.long)

        # Process edges
        edge_lists = {}
        for u, v, k, e_data in ag.G.edges(data=True, keys=True):
            u_cat = ag.G.nodes[u].get("category", "unknown_node")
            v_cat = ag.G.nodes[v].get("category", "unknown_node")
            edge_type = e_data.get("relationship", "unknown_edge")
            edge_triplet = (u_cat, edge_type, v_cat)

            if edge_triplet not in edge_lists:
                edge_lists[edge_triplet] = [[], []]

            edge_lists[edge_triplet][0].append(node_maps[u_cat][u])
            edge_lists[edge_triplet][1].append(node_maps[v_cat][v])

        for triplet, edge_index in edge_lists.items():
            data[triplet].edge_index = torch.tensor(edge_index, dtype=torch.long)

        data = T.ToUndirected()(data)
        return data

    def run_synthetic_training_smoke_test(
        self,
        pyg_data: HeteroData,
        epochs: int = 5,
        hidden_dim: int = 32
    ) -> Dict[str, Any]:
        """
        Executes a localized training run to verify gradient backpropagation, loss reduction,
        and checkpoint serialization on the HeteroGATv2 architecture.
        """
        metadata = pyg_data.metadata()
        model = create_hetero_gatv2(metadata, hidden_channels=hidden_dim, out_channels=3, num_heads=2)
        optimizer = optim.Adam(model.parameters(), lr=0.01)
        criterion = nn.CrossEntropyLoss()

        pipeline = TrainingPipeline(model, config={"seed": self.seed, "sandbox_mode": True})
        
        # Verify validate_data_for_training
        pipeline.validate_data_for_training(pyg_data)

        loss_history = []
        for ep in range(epochs):
            loss = pipeline.train_step(pyg_data, optimizer, criterion)
            loss_history.append(float(loss))

        # Save checkpoint strictly inside sandbox directory
        checkpoint_path = os.path.join(self.SANDBOX_DIR, "synthetic_dev_checkpoint.pt")
        pipeline.save_checkpoint(checkpoint_path)

        # Verify load checkpoint
        pipeline.load_checkpoint(checkpoint_path)

        # Evaluate model predictions
        model.eval()
        with torch.no_grad():
            out_dict = model(pyg_data.x_dict, pyg_data.edge_index_dict)
            file_preds = out_dict["file"].argmax(dim=-1).numpy()
            file_targets = pyg_data["file"].y.numpy()

        labeled_mask = file_targets >= 0
        y_true = file_targets[labeled_mask]
        y_pred = file_preds[labeled_mask]

        metrics = EvaluationMetrics.calculate_classification_metrics(y_true, y_pred)

        results = {
            "is_synthetic_development_artifact": True,
            "valid_for_empirical_claims": False,
            "provenance": "SYNTHETIC_DEVELOPMENT_ONLY",
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "epochs_trained": epochs,
            "initial_loss": loss_history[0] if loss_history else 0.0,
            "final_loss": loss_history[-1] if loss_history else 0.0,
            "metrics": metrics,
            "checkpoint_path": checkpoint_path,
            "warning": "DO NOT USE FOR EMPIRICAL EVALUATION OR PUBLISHED CLAIMS."
        }

        results_path = os.path.join(self.SANDBOX_DIR, "synthetic_training_smoke_results.json")
        with open(results_path, "w", encoding="utf-8") as f:
            json.dump(results, f, indent=2)

        return results
